const fs = require('node:fs');
const path = require('node:path');
const demo = path.resolve(__dirname,'..');
const workspace = path.resolve(demo,'../..');
const tooling = path.join(workspace,'.tooling');
const track = require('../src/landscape.js');

async function build(){
  const gd = await require(path.join(tooling,'gdcore/libGD.js'))();
  gd.ProjectHelper.initializePlatforms();
  const extension = require(path.join(tooling,'gdevelop-5.6.287/resources/GDJS/Runtime-sources/Extensions/3D/JsExtension.js'));
  gd.JsPlatform.get().addNewExtension(extension.createExtension(s=>s,gd));
  const project=gd.ProjectHelper.createNewGDJSProject();
  project.setName('Downhill Bike - Ridge Run');
  project.setDescription('A third-person mountain bike descent. Ride the ridge solo or take on a series of descents with up to three friends.');
  project.setPackageName('com.downhillbike.ridgerun');
  project.setGameResolutionSize(1280,720);
  project.setMaximumFPS(60);
  project.setMinimumFPS(15);
  project.setFirstLayout('RidgeRun');
  project.setLastCompilationDirectory(path.join(demo,'build'));
  const scene=project.insertNewLayout('RidgeRun',0);
  // Native editor landmarks indicate the track extent. The shared heightfield
  // and detailed meshes are generated by the JavaScript event at runtime.
  const landmarks=[['RidgeReference',0,'#467c93'],['ValleyReference',track.finish,'#c46a40']];
  for (const [index,[name,y]] of landmarks.entries()){
    scene.getObjects().insertNewObject(project,'Scene3D::Cube3DObject',name,index);
    const instance=scene.getInitialInstances().insertNewInitialInstance();
    instance.setObjectName(name);
    instance.setX((track.safeX(y)-4)*100);
    instance.setY(-y*100);
    instance.setZ(track.sample(track.safeX(y),y).z*100);
  }
  const files=['track.js','expedition.js','landscape.js','solids.js','bike.js','journey.js','mouse.js','bail.js','rider.js','dust.js','scenery.js','view.js','crew.js','runtime.js'];
  const source=files.map(file=>fs.readFileSync(path.join(demo,'src',file),'utf8')).join('\n\n');
  const event=scene.getEvents().insertNewEvent(project,'BuiltinCommonInstructions::JsCode',0);
  gd.asJsCodeEvent(event).setInlineCode(
    'if (!runtimeScene.__downhillBike) {\n'+source+'\n'+
    '  runtimeScene.__downhillBike = createBikeGame(runtimeScene);\n}\nruntimeScene.__downhillBike.tick();'
  );
  const serializer=new gd.SerializerElement();
  project.serializeTo(serializer);
  const data=JSON.parse(gd.Serializer.toJSON(serializer));
  serializer.delete();
  data.resources.resources.push({kind:'image',name:'landmark-white',file:'assets/white.png',smoothed:false,userAdded:true});
  const layout=data.layouts[0];
  for (const name of ['park_dirt','gravel_floor_04','forest_floor','mountain-sky']){
    data.resources.resources.push({kind:'image',name,file:'assets/runtime/'+name+'.jpg',smoothed:true,userAdded:true});
    // GDevelop discovers the texture in its resource preloader through this
    // editor object. The runtime heightfield shares it across the entire trail.
    layout.objects.push({
      name:'Surface_'+name,type:'Sprite',variables:[],behaviors:[],effects:[],updateIfNotVisible:false,
      animations:[{name:'Texture',useMultipleDirections:false,directions:[{
        looping:false,timeBetweenFrames:1,sprites:[{image:name,originPoint:{name:'origin',x:0,y:0},
          centerPoint:{name:'center',automatic:true,x:0,y:0},points:[],hasCustomCollisionMask:false,customCollisionMask:[]}]
      }]}]
    });
  }
  for (const [name,file] of [['bike-spokes','bicycle_spokes-1.ogg'],['bike-bell','rotating_bicycle_bell-1.ogg']]){
    data.resources.resources.push({kind:'audio',name,file:'assets/runtime/'+file,userAdded:true});
  }
  layout.r=164;layout.v=196;layout.b=199;
  Object.assign(layout.layers[0],{renderingType:'3d',cameraType:'perspective',
    camera3DFarPlaneDistance:600000,camera3DNearPlaneDistance:5,camera3DFieldOfView:57});
  for (const [name,,tint] of landmarks){
    const object=layout.objects.find(item=>item.name===name);
    Object.assign(object.content,{width:800,height:38,depth:365,materialType:'Basic',tint,
      isCastingShadow:false,isReceivingShadow:false});
    for(const face of ['front','back','left','right','top','bottom'])object.content[face+'FaceResourceName']='landmark-white';
  }
  data.properties.loadingScreen.showGDevelopSplash=false;
  data.properties.loadingScreen.backgroundColor=0x233936;
  data.properties.loadingScreen.minDuration=0.1;
  data.properties.watermark.showWatermark=false;
  fs.writeFileSync(path.join(demo,'downhill-bike.json'),JSON.stringify(data,null,2)+'\n');
  console.log('Wrote editable Downhill Bike GDevelop project.');
}
build().catch(error=>{console.error(error);process.exitCode=1;});
