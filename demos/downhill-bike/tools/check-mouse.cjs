const assert=require('node:assert/strict'),create=require('../src/mouse.js');
const M=require('../src/bike.js'),T=require('../src/track.js');
const flat={...T,rocks:[],sample:()=>({z:0,kind:'dirt',gap:false,jump:null}),reachedValley:()=>false};
const r=M.create(flat);Object.assign(r,{phase:'riding',vy:12,speed:12});
const mouse=create();mouse.begin(400,300,0);mouse.move(410,300,0);
assert.ok(Math.abs(mouse.steer(r))<.02,'Tiny drags should stay near neutral');
mouse.move(510,300,0);assert.ok(mouse.steer(r)>.5);
const target=mouse.state.targetYaw;
for(let i=0;i<240;i++)M.step(r,{steer:mouse.steer(r)},flat);
assert.ok(r.yaw>.20&&r.x>1,'Mouse intent should turn the physical bike');
assert.ok(Math.abs(r.yaw-target)<.05,'Holding the mouse still should converge, not spin indefinitely');
mouse.move(650,270,r.yaw);assert.equal(mouse.steer(r,-1,true),-1);
assert.ok(mouse.view(r.yaw).yaw>.1,'Keyboard steering must not erase mouse look');
const gaze=mouse.view(r.yaw).yaw;
mouse.move(690,270,r.yaw,false,true);
assert.ok(mouse.view(r.yaw).yaw>gaze,'Dragging while correcting with keys must still move the gaze');
assert.equal(mouse.steer(r),0,'Releasing a keyboard correction must not restore an old turn');
mouse.move(790,270,r.yaw);const velocity=[r.vx,r.vy,r.vz];
r.grounded=false;assert.equal(mouse.steer(r),0);assert.ok(mouse.view(r.yaw).yaw>.1);
assert.deepEqual([r.vx,r.vy,r.vz],velocity,'Free look must not redirect airborne momentum');
assert.equal(mouse.steer(r,-1,true),-1,'Keyboard air lean must remain available');
r.grounded=true;assert.equal(mouse.steer(r),0,'Landing must clear the free-look heading');
mouse.move(900,270,r.yaw);assert.equal(mouse.steer(r,0,false,true),0);
assert.equal(mouse.steer(r,0,false,false),0,'Leaving scout must not start steering');
mouse.move(1000,270,r.yaw);assert.ok(mouse.steer({...r,speed:25})<=.58);
mouse.release();assert.equal(mouse.steer(r),0);assert.deepEqual(mouse.view(r.yaw),{yaw:0,pitch:0});
mouse.begin(20,20,Math.PI-.01);mouse.move(90,20,Math.PI-.01);
assert.ok(mouse.steer({...r,yaw:-Math.PI+.01})>0,'Crossing the angle wrap must preserve turn direction');
console.log('Mouse steering converges through the bike solver; keyboard overrides, scout/air transitions, release, speed cap, and yaw wrap pass.');
