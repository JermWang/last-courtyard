const assert=require('node:assert/strict'),A=require('../src/animation.js');
const a=A.create(),base={grounded:true,distance:0};
const tick=(s={},dt=1/60)=>A.update(a,{...base,...s},dt);
assert.equal(tick().kind,'idle');
let contacts=0;for(let i=0;i<140;i++)contacts+=tick({distance:1}).step;
assert.equal(contacts,2,'two contacts per 140-unit walking cycle');
assert.equal(tick().kind,'idle');assert.equal(a.phase,0);
assert.equal(tick({drawing:true,draw:0.05}).frame,8);
assert.equal(tick({drawing:true,draw:0.2}).frame,9);
assert.equal(tick({drawing:true,draw:0.7}).frame,10);
assert.equal(tick({fired:true}).frame,11);
const fire=a.fire;tick({paused:true},2);assert.equal(a.fire,fire);tick({},2);assert.equal(a.fire,fire);
for(let i=0;i<15;i++)tick();assert.equal(a.pose.kind,'idle');
assert.equal(tick({grounded:false,vz:200}).kind,'jump');
assert.equal(tick({grounded:false,vz:-100}).kind,'fall');
assert.equal(tick({grounded:false,attached:true}).kind,'swing');
assert.equal(tick({landed:true}).kind,'land');
A.reset(a);assert.equal(tick({reeling:true}).kind,'reel');
tick({fired:true});A.reset(a);assert.equal(tick().kind,'idle');assert.equal(a.fire,0);
console.log('Animation tests passed: distance timing, action priorities, freeze, reset, reel and airborne states.');
